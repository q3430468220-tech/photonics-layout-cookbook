"""Command line: ``uv run photonics-cookbook <command>``.

Commands
--------
processes                       list shipped process files
show-process NAME               print the layer table of a process
check-pdk NAME                  compare a process with its upstream gdsfactory PDK
bootstrap-process MODULE -o F   draft a process YAML from any gdsfactory PDK
to-lumerical GDS --process P    write Lumerical scripts for a GDS file
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


def _floats(s: str) -> tuple[float, float]:
    a, b = (float(v) for v in s.split(","))
    return a, b


def cmd_processes(_: argparse.Namespace) -> int:
    from photonics_cookbook.process import available_processes, load_process

    for name in available_processes():
        p = load_process(name)
        print(f"{name:<30} {p.foundry} -- {p.platform}")
    return 0


def cmd_show(args: argparse.Namespace) -> int:
    from photonics_cookbook.process import load_process

    print(load_process(args.name).summary())
    return 0


def cmd_check(args: argparse.Namespace) -> int:
    from photonics_cookbook.process import load_process
    from photonics_cookbook.process.upstream import check_against_pdk

    proc = load_process(args.name)
    module, checks = check_against_pdk(proc)
    print(f"{proc.name} vs {module}.PDK.layers")
    bad = 0
    for c in checks:
        flag = "ok " if c.ok else "MISMATCH"
        bad += not c.ok
        print(f"  [{flag}] {c.role:<8} process {c.process_gds}  PDK {c.pdk_name} = {c.pdk_gds}")
    print("all layers match" if not bad else f"{bad} mismatch(es): update the process YAML")
    return 1 if bad else 0


def cmd_bootstrap(args: argparse.Namespace) -> int:
    import yaml

    from photonics_cookbook.process.upstream import bootstrap_from_pdk

    draft = bootstrap_from_pdk(args.module)
    text = (
        "# Draft generated by `photonics-cookbook bootstrap-process`. Complete every TODO:\n"
        "# rename layers to cookbook roles (core, slab, n, p, npp, ppp, via, metal ...),\n"
        "# set Lumerical material names, implant dopant/concentration, background stack.\n"
        + yaml.safe_dump(draft, sort_keys=False, allow_unicode=True)
    )
    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
        print(f"written {args.output}")
    else:
        print(text)
    return 0


def cmd_to_lumerical(args: argparse.Namespace) -> int:
    from photonics_cookbook.lumerical import export_lumerical

    cut = (_floats(args.cut[0]), _floats(args.cut[1])) if args.cut else None
    res = export_lumerical(
        args.gds,
        args.process,
        args.out,
        cell=args.cell,
        cut=cut,
        origin=_floats(args.origin) if args.origin else None,
        norm_length_um=args.norm_length,
        bend_radius_um=args.bend_radius,
        v_stop=args.v_stop,
    )
    print(res)
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="photonics-cookbook", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("processes", help="list shipped process files").set_defaults(fn=cmd_processes)
    s = sub.add_parser("show-process", help="print a process layer table")
    s.add_argument("name")
    s.set_defaults(fn=cmd_show)
    s = sub.add_parser("check-pdk", help="cross-check a process with its gdsfactory PDK")
    s.add_argument("name")
    s.set_defaults(fn=cmd_check)
    s = sub.add_parser("bootstrap-process", help="draft a process YAML from a gdsfactory PDK")
    s.add_argument("module", help="python module exposing PDK, e.g. cspdk.si220")
    s.add_argument("-o", "--output")
    s.set_defaults(fn=cmd_bootstrap)
    s = sub.add_parser("to-lumerical", help="GDS -> Lumerical scripts")
    s.add_argument("gds")
    s.add_argument("--process", required=True)
    s.add_argument("--out", help="output folder (default: next to the GDS)")
    s.add_argument("--cell")
    s.add_argument("--cut", nargs=2, metavar=("X0,Y0", "X1,Y1"), help="2D cut line for CHARGE / FDE (um)")
    s.add_argument("--origin", metavar="X,Y", help="point on the cut that becomes x = 0")
    s.add_argument("--norm-length", type=float, help="doped device length (um) for CHARGE")
    s.add_argument("--bend-radius", type=float, help="bend radius (um) for FDE")
    s.add_argument("--v-stop", type=float, default=-4.0)
    s.set_defaults(fn=cmd_to_lumerical)
    args = ap.parse_args(argv)
    from photonics_cookbook.process import ProcessError

    try:
        return int(args.fn(args) or 0)
    except (ProcessError, FileNotFoundError, ValueError) as err:
        print(f"error: {err}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
