"""Small helpers to emit Lumerical script (.lsf) text from Python."""

from __future__ import annotations

import datetime as _dt
import re

from photonics_cookbook import __version__

UM = 1e-6


def num(x: float) -> str:
    """Compact float literal (scientific if needed)."""
    return f"{float(x):.8g}"


def um(x: float) -> str:
    """Length in um -> Lumerical SI expression using the ``um`` variable."""
    return f"{float(x):.6g}*um"


def q(s: str) -> str:
    """Quote a string for Lumerical script."""
    if '"' in s:
        raise ValueError(f"double quotes are not allowed in Lumerical strings: {s!r}")
    return f'"{s}"'


def ident(s: str) -> str:
    """Make a safe Lumerical object name (letters, digits, underscore)."""
    out = re.sub(r"[^A-Za-z0-9_]", "_", s)
    return out if out and not out[0].isdigit() else f"_{out}"


def header(title: str, lines: list[str]) -> str:
    stamp = _dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    bar = "#" * 79
    body = [bar, f"#  {title}", "#  " + "-" * 75]
    body += [f"#  {ln}" if ln else "#" for ln in lines]
    body += [
        "#",
        f"#  Generated by photonics-layout-cookbook {__version__} on {stamp}.",
        "#  Do not edit by hand -- change the layout / process file and regenerate.",
        bar,
        "",
    ]
    return "\n".join(body)


